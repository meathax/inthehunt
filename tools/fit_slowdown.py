"""Fit the slowdown model from MAME measurements of the original program.

Input: TSV rows written by tools/mame_measure_passes.lua, one per logic pass
of the World program: busy CPU cycles from the pass-counter increment at
0:086C to the 0:084D wait loop, the master routine, the sprite count, the
actor routines in the list, video-RAM writes and palette banks stepped.

Model:  cycles = base[master] + sum(cost[routine] for each actor)
                 + per_sprite * sprites + per_vram * video-RAM writes
                 + per_fade * faded colours + per_copy * copied colours
fitted with non-negative least squares on 80 % of the passes; the other
20 % report the error and how often an overrun (a pass longer than one
board frame) is predicted. Output: src/world_slowdown_table.h.

  python tools/fit_slowdown.py build/mame/solo.tsv build/mame/duo.tsv
"""
import sys
import pathlib
import numpy as np
from scipy.optimize import nnls
from scipy.sparse import csr_matrix

FRAME = 9000000 * 424 * 262 / 6666666      # CPU cycles per board frame
ROOT = pathlib.Path(__file__).resolve().parents[1]


def load(paths):
    rows = []
    for path in paths:
        with open(path, encoding="utf-8") as f:
            next(f)
            for line in f:
                part = line.rstrip("\n").split("\t")
                if len(part) < 11:
                    continue
                start, cycles, frames, master, stage, sprites, handlers, vram, flags, fade, copy = part[:11]
                if int(start) < 600:       # power-on self test and uninitialised RAM
                    continue
                rows.append((int(cycles), master, int(sprites), handlers.split(";") if handlers else [],
                             int(vram), [int(v) for v in fade.split()], int(copy)))
    return rows


def main():
    rows = load(sys.argv[1:])
    masters = sorted({r[1] for r in rows})
    handlers = sorted({h for r in rows for h in r[3]})
    col = {("m", m): i for i, m in enumerate(masters)}
    for h in handlers:
        col[("h", h)] = len(col)
    sprite_col = len(col)
    vram_col, copy_col, fade_col = sprite_col + 1, sprite_col + 2, sprite_col + 3   # fade: 3 columns, one per mode
    n = sprite_col + 6
    rng = np.random.default_rng(1)
    test = rng.random(len(rows)) < 0.2

    def matrix(sel):
        data, ri, ci, y = [], [], [], []
        k = 0
        for r, use in zip(rows, sel):
            if not use:
                continue
            cnt = {}
            for h in r[3]:
                cnt[h] = cnt.get(h, 0) + 1
            ri.append(k); ci.append(col[("m", r[1])]); data.append(1.0)
            for h, c in cnt.items():
                ri.append(k); ci.append(col[("h", h)]); data.append(float(c))
            ri.append(k); ci.append(sprite_col); data.append(float(r[2]))
            ri.append(k); ci.append(vram_col); data.append(float(r[4]))
            for mode in range(3):
                ri.append(k); ci.append(fade_col + mode); data.append(float(r[5][mode]))
            ri.append(k); ci.append(copy_col); data.append(float(r[6]))
            y.append(float(r[0]))
            k += 1
        return csr_matrix((data, (ri, ci)), shape=(k, n)).toarray(), np.array(y)

    a, y = matrix(~test)
    scale = np.maximum(a.max(axis=0), 1.0)
    x, _ = nnls(a / scale, y, maxiter=20 * n)
    x = x / scale
    at, yt = matrix(test)
    pred = at @ x
    err = pred - yt
    r2 = 1 - np.sum(err ** 2) / np.sum((yt - yt.mean()) ** 2)
    over_true, over_pred = yt > FRAME, pred > FRAME
    print(f"passes {len(rows)} (test {int(test.sum())}), masters {len(masters)}, routines {len(handlers)}")
    print(f"test mean |error| {np.mean(np.abs(err)):.0f} cycles ({np.mean(np.abs(err)) / FRAME * 100:.1f}% of a frame), "
          f"median {np.median(np.abs(err)):.0f}, r^2 {r2:.3f}")
    print(f"overruns in test: actual {int(over_true.sum())}, predicted {int(over_pred.sum())}, "
          f"both {int(np.sum(over_true & over_pred))}, missed {int(np.sum(over_true & ~over_pred))}, "
          f"false {int(np.sum(~over_true & over_pred))}")
    print(f"slowdown frames in test: actual {int(np.floor(yt / FRAME).sum())}, predicted {int(np.floor(pred / FRAME).sum())}")
    print(f"per sprite {x[sprite_col]:.1f}, per VRAM write {x[vram_col]:.1f}, per faded colour (modes 0/1/2) "
          f"{x[fade_col]:.0f}/{x[fade_col + 1]:.0f}/{x[fade_col + 2]:.0f}, per copied colour {x[copy_col]:.0f} cycles")

    out = ROOT / "src" / "world_slowdown_table.h"
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by tools/fit_slowdown.py from MAME measurements of the original\n"
                f" * World program ({len(rows)} logic passes). Do not edit by hand.\n"
                f" * Held-out mean error {np.mean(np.abs(err)):.0f} cycles, r^2 {r2:.3f}. */\n")
        f.write(f"static const uint32_t slowdown_per_sprite = {int(round(x[sprite_col]))};\n")
        f.write(f"static const uint32_t slowdown_per_vram_write = {int(round(x[vram_col]))};\n")
        f.write("static const uint32_t slowdown_per_faded_colour[3] = {" +
                ", ".join(str(int(round(x[fade_col + m]))) for m in range(3)) + "};\n")
        f.write(f"static const uint32_t slowdown_per_copied_colour = {int(round(x[copy_col]))};\n")
        f.write(f"static const uint32_t slowdown_default_routine = "
                f"{int(round(np.median([x[col[('h', h)]] for h in handlers])))};   /* routines not seen in MAME */\n")
        f.write(f"static const uint32_t slowdown_default_base ={int(round(np.median([x[col[('m', m)]] for m in masters])))};\n")
        f.write("static const struct { uint16_t master; uint32_t cycles; } slowdown_base[] = {\n")
        for m in masters:
            f.write(f"    {{0x{m}, {int(round(x[col[('m', m)]]))}}},\n")
        f.write("};\nstatic const struct { uint32_t address; uint32_t cycles; } slowdown_cost[] = {\n")
        for h in handlers:
            f.write(f"    {{0x{h}, {int(round(x[col[('h', h)]]))}}},\n")
        f.write("};\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
