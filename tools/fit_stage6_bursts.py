"""Rebuild the stage 6 approach profile from FFmpeg playfield-difference metadata."""
import argparse
import csv
from pathlib import Path


def read_holds(path):
    prefix = "lavfi.signalstats.YAVG="
    with path.open(encoding="utf-8") as stream:
        differences = [float(line[len(prefix):]) for line in stream if line.startswith(prefix)]
    if len(differences) != 147741:
        raise ValueError("Expected the 147741 successive differences from the supplied recording")
    holds = [False] * len(differences)
    for i in range(1, len(differences) - 1):
        moving = max(differences[i - 1], differences[i + 1])
        holds[i] = moving > 1 and differences[i] < 0.25 * moving
    return holds


def generate(holds, windows):
    table, packed = [], []
    for i, row in enumerate(windows):
        start = int(row["start_diff_frame"])
        stop = int(row["end_diff_frame"])
        entry = int(row["entry_frame"])
        # Retain the half-window either side of the detector boundary so a
        # short peak keeps its measured rise and fall. Separate close peaks.
        left = max(entry, start - 15)
        right = stop + 15
        if i:
            left = max(left, (int(windows[i - 1]["end_diff_frame"]) + start) // 2)
        if i + 1 < len(windows):
            right = min(right, (stop + int(windows[i + 1]["start_diff_frame"])) // 2)
        # A hold at the left edge belongs to the preceding update. Include
        # that update or a borderline nine-in-thirty peak can become eight.
        while left > entry and holds[left]:
            left -= 1
        while holds[left]:
            left += 1
        counts = []
        for hold in holds[left:right]:
            if hold:
                counts[-1] += 1
            else:
                counts.append(0)
        if not counts or max(counts) > 3:
            raise ValueError(f'Unsupported held-refresh sequence in burst {row["burst"]}')
        enemy = "APPROACH_" + row["enemy"] if row["enemy"] else "0"
        table.append("    {%s, %s, %s, %d, %d, %d, %s}," % (
            row["camera_entry"], row["camera_onset"], row["camera_exit"],
            left - entry, len(counts), len(packed), enemy))
        for j in range(0, len(counts), 4):
            packed.append(sum(value << (2 * k) for k, value in enumerate(counts[j:j + 4])))
    lines = [
        "/* Generated by tools/fit_stage6_bursts.py. See docs/stage6-approach.md. */",
        "static const struct {",
        "    uint16_t entry, onset, exit, delay, length, profile_offset, enemy;",
        "} stage6_bursts[] = {", *table, "};", "",
        "/* Four game passes per byte, two bits of extra refreshes per pass. */",
        "static const uint8_t stage6_profile[] = {",
    ]
    for j in range(0, len(packed), 16):
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in packed[j:j+16]) + ",")
    return "\n".join([*lines, "};", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("metadata", type=Path)
    root = Path(__file__).resolve().parents[1]
    parser.add_argument("--windows", type=Path, default=root / "docs/stage6-approach-bursts.csv")
    parser.add_argument("--output", type=Path, default=root / "src/world_stage6_profile.h")
    args = parser.parse_args()
    with args.windows.open(newline="", encoding="utf-8") as stream:
        profile = generate(read_holds(args.metadata), list(csv.DictReader(stream)))
    args.output.write_text(profile, encoding="utf-8")
