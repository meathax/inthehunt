#!/usr/bin/env python3
"""Coverage ledger: handler entries the original program executes, per stage,
against the handlers the native build implements.

Reads every .local/ref/*/calls.txt written by ref_capture.lua and the case
labels in src/world_actors_*.c, src/world_stage*.c and src/world_common.c.
Writes docs/COVERAGE.md.  The reference recordings only reach what the capture
bot reached, so "seen" is a lower bound on what each stage needs."""
import collections, glob, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TITLE = range(0xA89D9, 0xA8ED9)  # world_title_actor range in world_dispatch.c


def native_handlers():
    found = {}
    files = sorted(glob.glob(str(ROOT / "src/world_actors_*.c")) + glob.glob(str(ROOT / "src/world_stage[0-9].c"))
                   + [str(ROOT / "src/world_common.c")])
    for path in files:
        for line in open(path, encoding="utf-8", errors="replace"):
            # Top-level labels only: four spaces of indentation.
            if line.startswith("    case 0x"):
                for value in re.findall(r"case (0x[0-9a-fA-F]+):", line):
                    found[int(value, 16)] = Path(path).name
    return found


def native_masters():
    text = "".join(open(ROOT / f"src/{n}", encoding="utf-8", errors="replace").read()
                   for n in ("world_frame.c", "world_title_master.c", "world_gameover.c", "world_title.c"))
    return {int(v, 16) for v in re.findall(r"master\s*==\s*(0x[0-9a-fA-F]+)", text)}


def main():
    native, masters_native = native_handlers(), native_masters()
    calls = collections.defaultdict(collections.Counter)    # stage -> handler -> calls
    masters = collections.defaultdict(collections.Counter)  # stage -> master -> passes
    runs = sorted(glob.glob(str(ROOT / ".local/ref/*/calls.txt")))
    for path in runs:
        for line in open(path):
            parts = line.split()
            if len(parts) < 4:
                continue
            master, stage = int(parts[2], 16), int(parts[3])
            masters[stage][master] += 1
            calls[stage].update(int(p, 16) for p in parts[4:])
    if not runs:
        sys.exit("no recordings under .local/ref; run tools/ref/run_capture.sh first")
    is_native = lambda a: a in native or a in TITLE
    out = ["# Coverage ledger", "",
           "Generated by `tools/ref/ledger.py` from reference recordings of the World set.",
           "A handler is an actor routine entry (linear address) called by the frame dispatcher;",
           "a master is the per-frame scene controller at RAM[80]. Recordings reach only what the",
           "capture bot reached, so these counts are a lower bound on what each stage needs.", "",
           "| Stage index | Handlers seen | Native | Missing | Calls native | Masters seen | Masters missing |",
           "|---|---|---|---|---|---|---|"]
    for stage in sorted(calls):
        seen = calls[stage]
        have = [a for a in seen if is_native(a)]
        total = sum(seen.values())
        covered = sum(seen[a] for a in have)
        miss_m = [m for m in masters[stage] if m not in masters_native]
        out.append(f"| {stage} | {len(seen)} | {len(have)} | {len(seen) - len(have)} | "
                   f"{100 * covered / total:.1f}% | {len(masters[stage])} | {len(miss_m)} |")
    all_seen = collections.Counter()
    for seen in calls.values():
        all_seen.update(seen)
    have = [a for a in all_seen if is_native(a)]
    out += ["", f"All stages: {len(all_seen)} distinct handlers seen, {len(have)} native, "
            f"{len(all_seen) - len(have)} missing. Native handlers never seen in a recording: "
            f"{len([a for a in native if a not in all_seen])}.", ""]
    for stage in sorted(calls):
        seen = calls[stage]
        missing = sorted((a for a in seen if not is_native(a)), key=lambda a: -seen[a])
        out += [f"## Stage index {stage}", ""]
        miss_m = sorted((m for m in masters[stage] if m not in masters_native), key=lambda m: -masters[stage][m])
        if miss_m:
            out += ["Masters without a native boundary: " +
                    ", ".join(f"`{m:04X}` ({masters[stage][m]} passes)" for m in miss_m), ""]
        if not missing:
            out += ["Every handler seen is native.", ""]
            continue
        out += ["| Missing handler | Calls | Also seen in stages |", "|---|---|---|"]
        for a in missing:
            others = [str(s) for s in sorted(calls) if s != stage and a in calls[s]]
            out.append(f"| `{a:05X}` | {seen[a]} | {', '.join(others) or '-'} |")
        out.append("")
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs/COVERAGE.md").write_text("\n".join(out), encoding="utf-8")
    print("\n".join(out[7:9 + len(calls) + 2]))


if __name__ == "__main__":
    main()
