"""Generate src/world_regions.inc from src/import/world_regions.json.

The native importer uses plain C tables: chip hashes and the (offset, length)
copy ranges that rebuild World chips from regional sets, stored as integers.
"""
import argparse
import base64
import gzip
import hashlib
import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def c_string(text):
    if not all(32 <= ord(c) < 127 and c not in '"\\' for c in text):
        raise SystemExit(f'unexpected characters in {text!r}')
    return f'"{text}"'


def sha1_bytes(text):
    raw = bytes.fromhex(text)
    if len(raw) != 20:
        raise SystemExit(f'bad SHA-1 {text}')
    return '{' + ','.join(f'0x{b:02x}' for b in raw) + '}'


def generate(source):
    raw = source.read_bytes()
    regions = json.loads(raw)
    out = ['/* Generated by tools/make_world_regions.py from src/import/world_regions.json. Do not edit. */',
           f'#define WORLD_REGIONS_METADATA_SHA256 "{hashlib.sha256(raw).hexdigest().upper()}"', '']
    region_rows = []
    for r, region in enumerate(regions):
        chip_rows = []
        for c, chip in enumerate(region['chips']):
            alt_rows = []
            for a, alt in enumerate(chip.get('alternates', [])):
                pairs = list(struct.iter_unpack('<ii', gzip.decompress(base64.b64decode(alt['copyRanges']))))
                if sum(length for _, length in pairs) != chip['size'] or any(
                        length <= 0 or offset < 0 or offset + length > chip['size'] for offset, length in pairs):
                    raise SystemExit(f"invalid copy ranges for {alt['set']} {chip['file']}")
                name = f'ranges_{r}_{c}_{a}'
                out.append(f'static const WorldCopyRange {name}[{len(pairs)}] = {{')
                for i in range(0, len(pairs), 8):
                    out.append('    ' + ','.join(f'{{{o},{n}}}' for o, n in pairs[i:i + 8]) + ',')
                out.append('};')
                alt_rows.append(f'    {{{c_string(alt["set"])}, {sha1_bytes(alt["sha1"])}, {name}, {len(pairs)}}},')
            alts = 'NULL'
            if alt_rows:
                alts = f'alternates_{r}_{c}'
                out.append(f'static const WorldAlternate {alts}[{len(alt_rows)}] = {{')
                out.extend(alt_rows)
                out.append('};')
            chip_rows.append(f'    {{{c_string(chip["file"])}, {chip["offset"]}, {chip["size"]}, {chip["stride"]}, '
                             f'{sha1_bytes(chip["sha1"])}, {alts}, {len(alt_rows)}}},')
            if chip['stride'] not in (1, 2) or chip['offset'] + (chip['size'] - 1) * chip['stride'] >= region['size']:
                raise SystemExit(f"chip {chip['file']} does not fit {region['name']}")
        out.append(f'static const WorldChip chips_{r}[{len(chip_rows)}] = {{')
        out.extend(chip_rows)
        out.append('};')
        region_rows.append(f'    {{{c_string(region["name"])}, {region["size"]}, chips_{r}, {len(chip_rows)}}},')
    out.append(f'static const WorldRegion world_region_list[{len(region_rows)}] = {{')
    out.extend(region_rows)
    out.append('};')
    out.append('const WorldRegionTable world_regions = {world_region_list, '
               f'{len(region_rows)}, WORLD_REGIONS_METADATA_SHA256}};')
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--input', type=Path, default=ROOT / 'src/import/world_regions.json')
    parser.add_argument('--output', type=Path, default=ROOT / 'src/world_regions.inc')
    args = parser.parse_args()
    text = generate(args.input)
    args.output.write_bytes(text.encode('ascii'))
    print(args.output)
